"""Pets with no resident art (Rammy 3, Burly Bear 6, Hawkster 16): one blob per chapter bank (palette, frame table, RLE pixels).
Run export (see docs) for assets/pet-common-<id> first: python pet_extra.py   ->  generated/pet_extra_art.h"""
import struct
from pathlib import Path
from PIL import Image
from camp_actors import pack
R=Path(__file__).resolve().parents[1];NL=chr(10)
PETS=(3,6,16);FOLLOW=(1,5,10);HAPPY=tuple(14+s for s in range(1,50,12))
BANKS=['arenas','keep','war','hubs','boss','forest','thieves','deer','flood','camp']
def main():
    imgs=[]
    for p in PETS:
        for f in FOLLOW+HAPPY:imgs.append(Image.open(R/f'assets/pet-common-{p}/{f}.png').convert('RGBA').resize((192,120),Image.Resampling.LANCZOS))
    atlas=Image.new('RGB',(192,120*len(imgs)))
    for i,im in enumerate(imgs):atlas.paste(im.convert('RGB'),(0,120*i),im.getchannel('A').point(lambda a:255 if a>=100 else 0))
    pal=atlas.quantize(colors=255,method=Image.Quantize.MEDIANCUT);prgb=pal.getpalette()[:765]
    ds=[0]+[0x8000|(prgb[i]>>3)|((prgb[i+1]>>3)<<5)|((prgb[i+2]>>3)<<10) for i in range(0,765,3)]
    data=bytearray();frames=[]
    for im in imgs:
        a=im.getchannel('A').point(lambda v:255 if v>=100 else 0);box=a.getbbox();x,y,r,b=box
        q=im.convert('RGB').quantize(palette=pal,dither=Image.Dither.NONE)
        block=bytes(q.getpixel((xx,yy))+1 if a.getpixel((xx,yy)) else 0 for yy in range(y,b) for xx in range(x,r))
        frames.append((len(data),x-96,y-88,r-x,b-y));data.extend(pack(block))
    blob=b''.join(struct.pack('<H',v) for v in ds)+b''.join(struct.pack('<IhhHH',*f) for f in frames)+bytes(data)
    n=len(FOLLOW)+len(HAPPY)
    h='#ifndef PET_EXTRA_ART_H'+NL+'#define PET_EXTRA_ART_H'+NL+'#include <stdint.h>'+NL+'/* Generated by tools/pet_extra.py: one copy of the blob per chapter bank. */'+NL
    h+=f'#define PET_EXTRA_FRAMES_PER_PET {n}'+NL+f'#define PET_EXTRA_FRAME_COUNT {len(frames)}'+NL+f'#define PET_EXTRA_PIXELS_MAX {max(f[3]*f[4] for f in frames)}'+NL
    h+=f'#define PET_EXTRA_FRAMES_OFFSET 512'+NL+f'#define PET_EXTRA_PIXELS_OFFSET {512+12*len(frames)}'+NL
    h+='static const uint8_t pet_extra_follow[%d]={%s};'%(len(FOLLOW),','.join(map(str,FOLLOW)))+NL
    h+='static const uint8_t pet_extra_happy[%d]={%s};'%(len(HAPPY),','.join(str(v-14) for v in HAPPY))+NL
    for b in BANKS:
        h+=f'static const uint8_t pet_extra_{b}[{len(blob)}] __attribute__((aligned(4)))={{'+NL+''.join(','.join(map(str,blob[j:j+32]))+','+NL for j in range(0,len(blob),32))+'};'+NL
    h+='#endif'+NL
    (R/'generated/pet_extra_art.h').write_text(h)
    print('frames',len(frames),'blob',len(blob),'max',max(f[3]*f[4] for f in frames))
if __name__=='__main__':main()
