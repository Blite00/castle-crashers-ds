"""LEVEL23 actor art: swimming knights, fat fish, bats, Catfish, rocks, fins, king boat. python flood_actors.py
Reads assets/flood-<costume> and assets/flood-extra-*, writes generated/flood_actor_art.h (pixel stream goes into the flood bank)."""
from PIL import Image
import rider_art as ra
from rider_art import pack,arr
R=ra.R
COSTUMES=['blue','orange','red','green']
def rng(a,b,s=1):return list(range(a,b,s))
def groups():
    g=[] # (name, [(dir,file,originx,originy)])
    for c in COSTUMES:
        d=f'flood-{c}'
        g.append((f'SWIM_STAND_{c.upper()}',[(d,1+i,275,282) for i in rng(0,12,2)]))
        g.append((f'SWIM_WALK_{c.upper()}',[(d,13+i,275,282) for i in rng(0,12,2)]))
        g.append((f'BATHEAD_{c.upper()}',[(d,25+i,275,282) for i in [0,2,4,6,8,10]]))
        g.append((f'LOGRIDE_{c.upper()}',[(d,36+i,407,400) for i in [0,4,8,12]]))
    e=lambda n,fs:[(f'flood-extra-{n}',f,400,400) for f in fs]
    g.append(('LOG',[('flood-extra-log',f,394,392) for f in (10,11,12)]))
    g.append(('FISH_IDLE',e('fishidle',rng(1,13,2))))
    g.append(('FISH_HIT',e('fishhit',rng(1,16,3))))
    g.append(('FISH_JUMP',e('fishjump',rng(1,75,11))))
    g.append(('FISH_CHARGE',e('fishcharge',rng(1,90,8))))
    g.append(('FISH_DIE',e('fishdie',rng(1,10,2))))
    g.append(('FIN',e('fin',[1])))
    g.append(('ROCK',e('rock',[1])))
    g.append(('BAT',e('bat',rng(1,7))))
    g.append(('BOAT',e('boat',[3,4])))
    g.append(('SPIT',e('catgo',[1,5,10,15,20])))
    g.append(('SPLASH',e('catgo',[26])))
    g.append(('BALL',e('cannon',[3])))
    g.append(('ANGRY',e('angry',[9,17,25,33,41,49,57,65,73,105])))
    g.append(('CAT_IDLE',e('cat218',rng(1,39,10))))
    g.append(('CAT_INTRO',e('cat241',rng(1,51,12))))
    g.append(('CAT_PUNCH1',e('cat280',rng(1,32,8))))
    g.append(('CAT_PUNCH2',e('cat248',rng(1,115,15))))
    g.append(('CAT_PUNCH3',e('cat263',rng(1,156,20))))
    g.append(('CAT_DIE',e('cat297',rng(1,150,30))))
    return g
def main():
    G=groups();images=[]
    for name,items in G:
        for d,f,ox,oy in items:images.append((Image.open(R/f'assets/{d}/{f}.png').convert('RGBA'),ox,oy))
    atlas=Image.new('RGB',(max(i.width for i,_,_ in images),sum(i.height for i,_,_ in images)),(0,0,0));y=0
    for im,_,_ in images:atlas.paste(im.convert('RGB'),(0,y),im.getchannel('A').point(lambda a:255 if a>=100 else 0));y+=im.height
    pal=atlas.quantize(colors=255,method=Image.Quantize.MEDIANCUT);prgb=pal.getpalette()[:765]
    ds=[0]+[0x8000|(prgb[i]>>3)|((prgb[i+1]>>3)<<5)|((prgb[i+2]>>3)<<10) for i in range(0,765,3)]
    data=bytearray();frames=[];seen={}
    for im,ox,oy in images:
        a=im.getchannel('A').point(lambda v:255 if v>=100 else 0);box=a.getbbox()
        if not box:frames.append((0,0,0,0,0));continue
        q=im.convert('RGB').quantize(palette=pal,dither=Image.Dither.NONE);x,y,r,b=box
        block=bytes(q.getpixel((xx,yy))+1 if a.getpixel((xx,yy)) else 0 for yy in range(y,b) for xx in range(x,r))
        key=(r-x,b-y,x-ox,y-oy,block)
        if key in seen:frames.append(frames[seen[key]]);continue
        seen[key]=len(frames);off=len(data);data.extend(pack(block));frames.append((off,x-ox,y-oy,r-x,b-y))
    out=['#ifndef FLOOD_ACTOR_ART_H\n#define FLOOD_ACTOR_ART_H\n#include <stdint.h>\n#include "castle_art.h"\n/* Generated by tools/flood_actors.py. */\n']
    out.append(f'#define FLOOD_ACTOR_PIXELS_MAX {max(f[3]*f[4] for f in frames)}\n')
    first=0;names=[];table=[]
    for name,items in G:names.append(f'FA_{name}={len(table)}');table.append((first,len(items)));first+=len(items)
    out.append('enum {'+','.join(names)+f',FA_GROUPS={len(table)}}};\n')
    out.append('typedef struct {uint16_t first,count;} FloodGroup;\n')
    out.append('static const FloodGroup flood_groups[%d]={'%len(table)+','.join('{%d,%d}'%t for t in table)+'};\n')
    out.append(arr('flood_actor_palette','uint16_t',ds));out.append(arr('flood_actor_pixels','uint8_t',list(data)))
    out.append('static const ArtFrame flood_actor_frames[%d]={'%len(frames)+','.join('{%d,%d,%d,%d,%d}'%f for f in frames)+'};\n')
    out.append('''static inline int flood_actor_decode(unsigned id,uint8_t*out){
 if(id>=%d||!out)return 0;
 const ArtFrame*f=&flood_actor_frames[id];unsigned at=f->offset,left=(unsigned)f->w*f->h;
 while(left){
  if(at>=sizeof(flood_actor_pixels))return 0;
  unsigned token=flood_actor_pixels[at++],n=(token&127)+1;if(n>left)return 0;
  if(token&128){if(at>=sizeof(flood_actor_pixels))return 0;unsigned v=flood_actor_pixels[at++];for(unsigned j=0;j<n;j++)*out++=(uint8_t)v;}
  else{if(n>sizeof(flood_actor_pixels)-at)return 0;for(unsigned j=0;j<n;j++)*out++=flood_actor_pixels[at++];}
  left-=n;
 }return 1;
}
#endif
'''%len(frames))
    (R/'generated/flood_actor_art.h').write_text(''.join(out))
    print('frames',len(frames),'distinct',len(seen),'pixel bytes',len(data),'max',max(f[3]*f[4] for f in frames))
if __name__=='__main__':main()
