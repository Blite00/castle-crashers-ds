"""Pack half-scale genuine pet/shovel frames; no synthesized pose or heap decoder.

Run export_pet_dig.py first. Indexed DS palette conversion matches existing art;
compression is lossless relative to those indexed source raster exports.
"""
from pathlib import Path
import ast,pickle,json,hashlib,struct
import numpy as np
from PIL import Image
R=Path(__file__).resolve().parents[1]
source=(R/'tools/convert_assets.py').read_text();tree=ast.parse(source);ns={}
for node in tree.body:
 if isinstance(node,ast.FunctionDef) or isinstance(node,ast.Assign) and any(isinstance(t,ast.Name) and t.id=='KNIGHT_DECODER' for t in node.targets):
  exec(compile(ast.Module(body=[node],type_ignores=[]),'<codec>','exec'),ns)
def arr(n,t,v):return f'static const {t} {n}[{len(v)}]={{'+','.join(map(str,v))+'};\n'
def build(kind,files,percolor,palette=None):
 ims=[Image.open(R/f'assets/{folder}/{n}.png').convert('RGBA').resize((192,120),Image.Resampling.LANCZOS) for folder,n in files]
 if palette is None:
  atlas=Image.new('RGB',(192,120*len(ims)))
  for i,im in enumerate(ims):atlas.paste(im,(0,120*i),im.getchannel('A'))
  p=atlas.quantize(colors=255,method=Image.Quantize.MEDIANCUT).getpalette()[:765]
  palette=[0]+[32768|(p[i]>>3)|((p[i+1]>>3)<<5)|((p[i+2]>>3)<<10) for i in range(0,765,3)]
 q=Image.new('P',(1,1));rgb=[];canonical={};remap=[]
 for i,c in enumerate(palette):
  canonical.setdefault(c,i);remap.append(canonical[c]);c=palette[1] if i==0 else c;rgb.extend(((c&31)*255//31,((c>>5)&31)*255//31,((c>>10)&31)*255//31))
 q.putpalette(rgb);data=[];meta=[];raws=[];hashes=[];pnghash=[]
 for im,(folder,n) in zip(ims,files):
  a=np.array(im.getchannel('A'))>=100;v=np.array(im.convert('RGB').quantize(palette=q,dither=Image.Dither.NONE));v[v==0]=1;v[~a]=0;v=np.take(remap,v).astype(np.uint8)
  ys,xs=np.where(v);x,y,rr,b=int(xs.min()),int(ys.min()),int(xs.max())+1,int(ys.max())+1
  assert x>0 and y>0 and rr<192 and b<120,(folder,n,x,y,rr,b)
  raw=v[y:b,x:rr].tobytes();raws.append(raw);meta.append((len(data),x-96,y-88,rr-x,b-y));data.extend(ns['pack'](raw))
  hv=2166136261
  for value in raw:hv=((hv^palette[value])*16777619)&0xffffffff
  hashes.append(hv);pnghash.append(hashlib.sha256((R/f'assets/{folder}/{n}.png').read_bytes()).hexdigest())
 delta,dm,bases=ns['knight_color_delta'](data,meta,percolor)
 pixels,frames,lengths,tables,trees=ns['knight_huffman_encode'](delta,dm)
 h=f'/* Generated by convert_pet_dig.py from actual source timelines. */\n#ifndef {kind.upper()}_ART_H\n#define {kind.upper()}_ART_H\n#include "castle_art.h"\n#include <string.h>\n'
 h+=f'#define {kind.upper()}_FRAME_PIXELS_MAX {max(w*hh for _,x,y,w,hh in meta)}\n#define {kind.upper()}_FRAME_COUNT {len(frames)}\n'
 if kind=='pet':h+=arr('pet_palette','uint16_t',palette)
 else:h+='#define dig_palette knight_palette\n'
 h+=arr(kind+'_pixels','uint8_t',pixels)
 h+=f'static const ArtFrame {kind}_frames[{len(frames)}]={{'+','.join('{%d,%d,%d,%d,%d}'%f for f in frames)+'};\n'
 h+=arr(kind+'_frame_bases','uint16_t',bases)
 h+=ns['knight_codec_tables'](arr,lengths,tables,trees).replace('knight_',kind+'_')
 h+=ns['KNIGHT_DECODER'].replace('knight_',kind+'_').replace('KNIGHT_',kind.upper()+'_')
 if kind=='pet':
  h+=arr('pet_follow_samples','uint8_t',FOLLOW)+arr('pet_happy_samples','uint8_t',HAPPY)+arr('pet_dig_samples','uint8_t',PETDIG)
  h+='''/* Follow and lost share the authored 14-frame hovering body. */
enum {PET_ART_FOLLOW=0,PET_ART_HAPPY=1,PET_ART_DIG=2};
static inline unsigned pet_art_frame(unsigned source_id,unsigned pose,unsigned tick){
 if(source_id!=17&&source_id!=24&&source_id!=2&&source_id!=9&&source_id!=21)return PET_FRAME_COUNT;
 unsigned base=source_id==24?18:source_id==2?42:source_id==9?60:source_id==21?78:0,sample=0,count=5;const uint8_t*frames=pet_follow_samples;
 if(pose==PET_ART_HAPPY){base+=5;frames=pet_happy_samples;count=13;tick=tick<49?tick:48;}
 else if(pose==PET_ART_DIG&&source_id==24){base=36;frames=pet_dig_samples;count=6;tick%=16;}
 else tick%=14;
 while(sample+1<count&&frames[sample+1]<=tick+1)sample++;
 return base+sample;
}
'''
 else:
  h+=arr('dig_source_frames','uint8_t',DIG_FRAMES)
  h+='''static inline unsigned dig_art_frame(unsigned color,unsigned source_frame){
 if(color>=4)return DIG_FRAME_COUNT;
 unsigned sample=0;while(sample+1<sizeof(dig_source_frames)&&dig_source_frames[sample+1]<=source_frame)sample++;
 return color*sizeof(dig_source_frames)+sample;
}
'''
 h+='#endif\n';(R/f'generated/{kind}_art.h').write_text(h)
 (R/f'generated/{kind}-art-test-hashes.bin').write_bytes(struct.pack('<'+'I'*len(hashes),*hashes))
 size=len(pixels)+len(frames)*16+3064+(512 if kind=='pet' else 0)
 audit=dict(frames=len(frames),compressed_bytes=len(pixels),estimated_static_bytes=size,max_pixels=max(w*hh for _,x,y,w,hh in meta),source_frames=files,source_png_sha256=pnghash,indexed_sha256=[hashlib.sha256(x).hexdigest() for x in raws])
 (R/f'generated/{kind}-art-audit.json').write_text(json.dumps(audit,indent=2));print(kind,size,'compressed',len(pixels),'max',audit['max_pixels'])
DIG_FRAMES=[1,7,13,19,25,31,34,39,45,51,57,63,69,76]
FOLLOW=[1,4,7,10,13]
HAPPY=list(range(1,50,4))
PETDIG=[1,4,7,10,13,16]
if __name__=='__main__':
 build('pet',[(f'pet-common-{pet}',n) for pet in (17,24) for n in FOLLOW+[14+n for n in HAPPY]]+[('pet-common-24',63+n) for n in PETDIG]+[('pet-common-2',n) for n in FOLLOW+[14+n for n in HAPPY]]+[(f'pet-common-{pet}',n) for pet in (9,21) for n in FOLLOW+[14+n for n in HAPPY]],96)
 build('dig',[(f'dig-common-{c}',n) for c in ('blue','orange','red','green') for n in DIG_FRAMES],len(DIG_FRAMES),pickle.loads((R/'build/held-base.pkl').read_bytes())['palette'])
