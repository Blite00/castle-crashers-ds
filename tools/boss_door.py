"""LEVEL7 bossdoor2 (sprite 202) intro animation: frames 2..170 (label knock at 2) of the door, the little barbarians that fall in front of it and
the door falling on them, plus a door-only picture for the time before the knock. Origin = the sprite origin; zoom 0.5 (DS pixels).
python boss_door.py prepare | convert"""
from pathlib import Path
import xml.etree.ElementTree as ET,sys,hashlib
from PIL import Image
import rider_art as ra
from rider_art import pack,arr
R=ra.R
STRIDE=3
def prepare():
    r=ET.parse(R/'assets/extracted/level7-full.xml').getroot();tags=r.find('tags')
    defs=[x for x in tags if x.get('type','').startswith('Define')];tags.clear();tags.extend(defs)
    p=ET.SubElement(tags,'item',type='PlaceObject2Tag',characterId='202',depth='1',forceWriteAsLong='false',placeFlagHasCharacter='true',placeFlagHasMatrix='true',placeFlagMove='false',placeFlagHasClipActions='false',placeFlagHasClipDepth='false',placeFlagHasColorTransform='false',placeFlagHasName='false',placeFlagHasRatio='false')
    ET.SubElement(p,'matrix',type='MATRIX',hasRotate='false',hasScale='false',translateX='0',translateY='0',rotateSkew0='0.0',rotateSkew1='0.0',scaleX='1.0',scaleY='1.0',nTranslateBits='1',nRotateBits='0',nScaleBits='0')
    for _ in range(170):ET.SubElement(tags,'item',type='ShowFrameTag',forceWriteAsLong='false')
    r.set('frameCount','170');rect=r.find('displayRect')
    for k,v in dict(Xmin=-8000,Xmax=8000,Ymin=-12000,Ymax=4000).items():rect.set(k,str(v))
    xml=R/'assets/extracted/boss-door.xml';ET.ElementTree(r).write(xml,encoding='utf-8',xml_declaration=True)
    swf=xml.with_suffix('.swf');out=R/'assets/boss-door'
    ra.ffdec('-xml2swf',str(xml),str(swf));ra.ffdec('-zoom','0.5','-ignorebackground','-export','frame',str(out),str(swf));print(len(list(out.glob('*.png'))))
OX,OY=200,300 # origin in the exported image: 8000/20*0.5, 12000/20*0.5
def convert():
    keys=[10]+list(range(2,171,STRIDE))+[170]
    base=Image.open(R/'assets/boss-door/10.png').convert('RGBA');bp=base.load()
    for yy in range(base.height):
        for xx in range(0,OX-30):bp[xx,yy]=(0,0,0,0) # the splash left of the door is not part of the door
    prepared=[]
    for f in keys:
        im=Image.open(R/f'assets/boss-door/{f}.png').convert('RGBA');kind=1
        if f!=10:
            px=im.load();lost=0;diff=Image.new('RGBA',im.size,(0,0,0,0));dp=diff.load()
            for yy in range(im.height):
                for xx in range(im.width):
                    b=bp[xx,yy];c=px[xx,yy];bo=b[3]>=100;co=c[3]>=100
                    if bo and not co:lost+=1
                    elif co and (not bo or sum(abs(b[k]-c[k]) for k in range(3))>24):dp[xx,yy]=c
            if lost<=12:im=diff;kind=0 # only what is added to the standing door
        prepared.append((f,im,kind))
    flat=Image.new('RGB',(max(i.width for _,i,_ in prepared),sum(i.height for _,i,_ in prepared)),(0,0,0));y=0
    for _,im,_ in prepared:flat.paste(im.convert('RGB'),(0,y),im.getchannel('A').point(lambda a:255 if a>=100 else 0));y+=im.height
    pal=flat.quantize(colors=255,method=Image.Quantize.MEDIANCUT);prgb=pal.getpalette()[:765]
    ds=[0]+[0x8000|(prgb[i]>>3)|((prgb[i+1]>>3)<<5)|((prgb[i+2]>>3)<<10) for i in range(0,765,3)]
    data=bytearray();frames=[];index={};seq=[]
    for f,im,kind in prepared:
        a=im.getchannel('A').point(lambda v:255 if v>=100 else 0);box=a.getbbox()
        if not box:frames.append((0,0,0,0,0));seq.append((len(frames)-1,kind));continue
        q=im.convert('RGB').quantize(palette=pal,dither=Image.Dither.NONE);x,y,r,b=box
        block=bytes(q.getpixel((xx,yy))+1 if a.getpixel((xx,yy)) else 0 for yy in range(y,b) for xx in range(x,r))
        key=(r-x,b-y,x,y,block)
        if key in index:seq.append((index[key],kind));continue
        index[key]=len(frames);seq.append((len(frames),kind));frames.append((len(data),x-OX,y-OY,r-x,b-y));data.extend(pack(block))
    # timeline: entry k of seq belongs to source frame keys[k]
    table=[]
    for f,(s,k) in zip(keys,seq):table.append((f,s,k))
    h=['#ifndef BOSS_DOOR_ART_H','#define BOSS_DOOR_ART_H','#include <stdint.h>','#include "castle_art.h"','/* Generated by tools/boss_door.py from LEVEL7 sprite 202 (bossdoor2). Origin = the door sprite origin, DS pixels. */',
       f'#define BOSS_DOOR_PIXELS_MAX {max(f[3]*f[4] for f in frames)}',f'#define BOSS_DOOR_STRIDE {STRIDE}',f'#define BOSS_DOOR_STEPS {len(table)}']
    h.append('/* source frame, picture index, kind (0 = drawn over the door alone, 1 = replaces it): step 0 is the door alone (before the knock), then frames 2.. every STRIDE, then the last */')
    h.append('static const uint16_t boss_door_steps[%d][3]={'%len(table)+','.join('{%d,%d,%d}'%t for t in table)+'};')
    h.append(arr('boss_door_palette','uint16_t',ds));h.append(arr('boss_door_pixels','uint8_t',list(data)))
    h.append('static const ArtFrame boss_door_frames[%d]={'%len(frames)+','.join('{%d,%d,%d,%d,%d}'%f for f in frames)+'};')
    h.append('''static inline int boss_door_decode(unsigned id,uint8_t*out){
 if(id>=%d||!out)return 0;
 const ArtFrame*f=&boss_door_frames[id];unsigned at=f->offset,left=(unsigned)f->w*f->h;
 while(left){
  if(at>=sizeof(boss_door_pixels))return 0;
  unsigned token=boss_door_pixels[at++],n=(token&127)+1;if(n>left)return 0;
  if(token&128){if(at>=sizeof(boss_door_pixels))return 0;unsigned v=boss_door_pixels[at++];for(unsigned j=0;j<n;j++)*out++=(uint8_t)v;}
  else{if(n>sizeof(boss_door_pixels)-at)return 0;for(unsigned j=0;j<n;j++)*out++=boss_door_pixels[at++];}
  left-=n;
 }return 1;
}
#endif'''%len(frames))
    (R/'generated/boss_door_art.h').write_text(chr(10).join(h)+chr(10));print('steps',len(table),'pictures',len(frames),'bytes',len(data),'max',max(f[3]*f[4] for f in frames))
if __name__=='__main__':{'prepare':prepare,'convert':convert}[sys.argv[1]]()
