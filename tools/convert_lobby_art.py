"""Original multiplayer lobby panel (LOBBY.swf): the gold portrait frame (sprite 199), knight portraits (sprite 180 frames
104-107, the framed colour-background poses of green/red/blue/orange), the up/down chevrons (235) and the ready badges (197).
Requires the FFDec sprite export in build/lobby/LOBBY (java -jar ffdec-cli.jar -format sprite:png -export sprite build/lobby/LOBBY assets/extracted/LOBBY.swf).
Output: generated/lobby_art.h, one 255 colour palette and RLE-packed bitmaps scaled by K to fit two panels on the 256x192 screen."""
from pathlib import Path
from PIL import Image
import numpy as np
R=Path(__file__).resolve().parents[1];X=R/'build/lobby/LOBBY'
K=0.35
def sprite(n,frame=1):return Image.open(X/f'DefineSprite_{n}/{frame}.png').convert('RGBA')
def scaled(im,s):
    w,h=max(1,round(im.width*s)),max(1,round(im.height*s));return im.resize((w,h),Image.Resampling.LANCZOS)
panel=sprite(199);a=np.array(panel)[:,:,3]
# Window = the transparent hole found by flood fill from the middle of the frame.
from collections import deque
seen=np.zeros(a.shape,bool);q=deque([(200,119)]);seen[200,119]=True
while q:
    y,x=q.popleft()
    for dy,dx in((1,0),(-1,0),(0,1),(0,-1)):
        ny,nx=y+dy,x+dx
        if 0<=ny<a.shape[0] and 0<=nx<a.shape[1] and not seen[ny,nx] and a[ny,nx]<128:seen[ny,nx]=True;q.append((ny,nx))
ys,xs=np.where(seen);wx0,wy0,wx1,wy1=xs.min(),ys.min(),xs.max()+1,ys.max()+1
# Ready badge position: the red pixels of the frame's baked X badge.
rgb=np.array(panel)[:,:,:3].astype(int);red=(rgb[:,:,0]>170)&(rgb[:,:,1]<60)&(rgb[:,:,2]<60)&(a>200);by,bx=np.where(red);bcx,bcy=(bx.min()+bx.max())/2,(by.min()+by.max())/2
panel_s=scaled(panel,K)
win=(round(wx0*K),round(wy0*K),round(wx1*K)-round(wx0*K),round(wy1*K)-round(wy0*K))
M=11 # The portrait runs under the frame by M pixels so no wood shows around it.
win2=(win[0]-M,win[1]-M,win[2]+2*M,win[3]+2*M)
port=[]
for frame in (106,107,105,104): # blue, orange, red, green = KNIGHT_BLUE..KNIGHT_GREEN
    p=sprite(180,frame);p=p.crop(p.getchannel('A').point(lambda v:255 if v>=40 else 0).getbbox());s=max(win2[2]/p.width,win2[3]/p.height);p2=scaled(p,s);left=(p2.width-win2[2])//2;top=(p2.height-win2[3])//2;port.append(p2.crop((left,top,left+win2[2],top+win2[3])))
chev=scaled(sprite(235),K)
badge_scale=0.7557*K;badges=[scaled(sprite(197,i),badge_scale) for i in (1,2,3)]
items=[panel_s]+port+[chev]+badges
flat=Image.new('RGB',(max(i.width for i in items),sum(i.height for i in items)),(0,0,0));y=0
for im in items:flat.paste(im.convert('RGB'),(0,y),im.getchannel('A').point(lambda v:255 if v>=100 else 0));y+=im.height
pal=flat.quantize(colors=255,method=Image.Quantize.MEDIANCUT);prgb=pal.getpalette()[:765]
ds=[0]+[0x8000|(prgb[i]>>3)|((prgb[i+1]>>3)<<5)|((prgb[i+2]>>3)<<10) for i in range(0,765,3)]
def pack(block):
    out=bytearray();i=0
    while i<len(block):
        run=1
        while run<128 and i+run<len(block) and block[i+run]==block[i]:run+=1
        if run>=3:out.extend([127+run,block[i]]);i+=run
        else:
            start=i;i+=run
            while i<len(block) and i-start<128:
                if i+2<len(block) and block[i]==block[i+1]==block[i+2]:break
                i+=1
            out.append(i-start-1);out.extend(block[start:i])
    return out
data=bytearray();frames=[]
for im in items:
    al=im.getchannel('A').point(lambda v:255 if v>=100 else 0);q=im.convert('RGB').quantize(palette=pal,dither=Image.Dither.NONE)
    block=bytes(q.getpixel((x,y))+1 if al.getpixel((x,y)) else 0 for y in range(im.height) for x in range(im.width))
    frames.append((len(data),im.width,im.height));data.extend(pack(block))
names=['PANEL','PORTRAIT_BLUE','PORTRAIT_ORANGE','PORTRAIT_RED','PORTRAIT_GREEN','CHEVRONS','BADGE_X','BADGE_OK','BADGE_WAIT']
h=['#ifndef LOBBY_ART_H','#define LOBBY_ART_H','#include <stdint.h>','/* Generated by tools/convert_lobby_art.py from the original LOBBY.swf panel. */',
   'enum {'+','.join('LOBBY_ART_'+n for n in names)+',LOBBY_ART_COUNT};',
   f'#define LOBBY_ART_PIXELS_MAX {max(f[1]*f[2] for f in frames)}',
   f'#define LOBBY_PORTRAIT_X {win2[0]}\n#define LOBBY_PORTRAIT_Y {win2[1]}\n#define LOBBY_WINDOW_X {win[0]}\n#define LOBBY_WINDOW_Y {win[1]}\n#define LOBBY_WINDOW_W {win[2]}\n#define LOBBY_WINDOW_H {win[3]}',
   f'#define LOBBY_BADGE_CX {round(bcx*K)}\n#define LOBBY_BADGE_CY {round(bcy*K)}']
def arr(n,t,v):return f'static const {t} {n}[{len(v)}]={{\n'+''.join(','.join(map(str,v[i:i+24]))+',\n' for i in range(0,len(v),24))+'};\n'
h.append(arr('lobby_palette','uint16_t',ds));h.append(f'#define LOBBY_PIXELS_SIZE {len(data)}u /* The packed bitmaps live in nitrofiles/lobby.bin, read when the lobby opens. */')
(R/'nitrofiles/lobby.bin').write_bytes(bytes(data))
h.append(f'typedef struct {{uint32_t offset;uint16_t w,h;}} LobbyArtFrame;\nstatic const LobbyArtFrame lobby_frames[{len(frames)}]={{'+','.join('{%d,%d,%d}'%f for f in frames)+'};')
h.append('''static inline int lobby_decode(const uint8_t *lobby_pixels,unsigned id,uint8_t*out){
 if(!lobby_pixels||id>=LOBBY_ART_COUNT||!out)return 0;
 const LobbyArtFrame*f=&lobby_frames[id];unsigned at=f->offset,left=(unsigned)f->w*f->h;
 while(left){
  if(at>=LOBBY_PIXELS_SIZE)return 0;
  unsigned token=lobby_pixels[at++],n=(token&127)+1;if(n>left)return 0;
  if(token&128){if(at>=LOBBY_PIXELS_SIZE)return 0;unsigned v=lobby_pixels[at++];for(unsigned j=0;j<n;j++)*out++=(uint8_t)v;}
  else{if(n>LOBBY_PIXELS_SIZE-at)return 0;for(unsigned j=0;j<n;j++)*out++=lobby_pixels[at++];}
  left-=n;
 }return 1;
}
#endif''')
(R/'generated/lobby_art.h').write_text('\n'.join(h)+'\n')
print('panel',panel_s.size,'window',win,'badge',(round(bcx*K),round(bcy*K)),'bytes',len(data),'frames',[(f[1],f[2]) for f in frames])
# Preview
S=Image.new('RGBA',(256,192),(110,80,60,255))
for n,xx in enumerate((38,134)):
    pi=port[n*2%4];S.alpha_composite(pi,(xx+win2[0],4+win2[1]));S.alpha_composite(panel_s,(xx,4));S.alpha_composite(chev,(xx+(panel_s.width-chev.width)//2,4+win[1]+(win[3]-chev.height)//2))
    b=badges[1 if n==0 else 0];S.alpha_composite(b,(xx+round(bcx*K)-b.width//2,4+round(bcy*K)-b.height//2))
S.resize((768,576),Image.NEAREST).save(R/'build/lobby_preview.png')
