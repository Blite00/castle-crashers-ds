"""Destructible scenery of Thieves Forest and Forest Entrance: grass (f_RegisterGrass) and the treasure chests (f_SetChest).

Reads the converted foreground layer tables, groups the pieces of each source object by depth and writes generated/break_points.h:
one row per object {depth, x centre, ground y, width, height, kind} sorted by x. The runtime hits, hides and replaces them by their
index; thieves has 13 grass tufts and 3 chests, forest 19 grass tufts."""
from pathlib import Path
import re,struct
R=Path(__file__).resolve().parents[1]
LEVELS=[('thieves','thieves_art.h',[(77,0),(188,1)]),('forest','forest_art.h',[(76,0)])]
out=['#ifndef BREAK_POINTS_H','#define BREAK_POINTS_H','#include <stdint.h>','/* Generated by tools/break_points.py. kind 0 grass, 1 chest. */','typedef struct {int16_t depth,x,y,w,h;uint8_t kind,source_low;} BreakPoint;']
for name,header,kinds in LEVELS:
    s=(R/'generated'/header).read_text()
    key=f'campaign_{name}_fg_layers_data'
    m=re.search(r'static const uint8_t '+key+r'\s*\[(\d+)\][^=]*=\s*\{(.*?)\};',s,re.S)
    data=bytes(map(int,re.findall(r'\d+',m[2])));n=len(data)//28
    pieces={}
    for k in range(n):
        x,y,w,h,d=struct.unpack_from('<5h',data,k*28);source,placement=struct.unpack_from('<HH',data,k*28+20)
        for sid,kind in kinds:
            if source==sid:pieces.setdefault((d,kind,sid),[]).append((x,y,x+w,y+h))
    rows=[]
    for (d,kind,sid),ps in pieces.items():
        ps.sort();cur=None
        for item in ps+[None]:
            if item and cur and item[0]<=cur[2]+3:cur=[min(cur[0],item[0]),min(cur[1],item[1]),max(cur[2],item[2]),max(cur[3],item[3])];continue
            if cur:rows.append(((cur[0]+cur[2])//2,d,cur[3],cur[2]-cur[0],cur[3]-cur[1],kind,sid))
            cur=list(item) if item else None
    rows.sort()
    print(name,len(rows),[(r[0],r[5]) for r in rows])
    out.append(f'#define BREAK_{name.upper()}_COUNT {len(rows)}')
    out.append(f'static const BreakPoint break_{name}[{len(rows)}]={{'+','.join('{%d,%d,%d,%d,%d,%d,%d}'%(r[1],r[0],r[2],r[3],r[4],r[5],r[6]&255) for r in rows)+'};')
out.append('#endif')
(R/'generated/break_points.h').write_text('\n'.join(out)+'\n')
