"""LEVEL22 actor art: deer, the four knights riding it, the Mill Monster, logs and walls. python deer_actors.py
Reads assets/deer-<costume>, assets/deer-mount and assets/deer-extra-*, writes generated/deer_actor_art.h (pixel stream goes into the deer bank)."""
from pathlib import Path
from PIL import Image
import rider_art as ra
from rider_art import pack,arr
R=ra.R
COSTUMES=['blue','orange','red','green']
RIDER_STARTS={'poo':12,'walk':1,'toss':15,'slam':39,'scared':83,'dock':93,'mount':148}
RIDER_KEYS={'walk':list(range(11)),'toss':[0,3,6,9,12,15,19,23],'slam':[0,4,8,12,16,20,26,32,38,43],'scared':[0,2,4,6,9],'dock':[0,6,12,18,24,30,36,42,48,54],'mount':[0,2,4,6,8,10,13],'poo':[0,1,2]}
DEER_STARTS={'poop':13,'idle':1,'walk':2,'jump':16,'dock':40,'scared':114}
DEER_KEYS={'idle':[0],'walk':list(range(11)),'jump':[0,3,6,9,12,15,19,23],'dock':[0,6,12,18,24,30,36,42,48,56,64,73],'scared':[0],'poop':[0,1,2]}
MON=[196,200,210,225,242,260,280,285,289,296,305,316]
def shaft(im):
    out=Image.new('RGBA',im.size,(0,0,0,0));p=im.load();o=out.load()
    for y in range(im.height):
        for x in range(im.width):
            r,g,b,a=p[x,y]
            if 10<=a<170:o[x,y]=(255,236,140,255)
    return out
def solid(im):
    out=im.copy();p=out.load()
    for y in range(out.height):
        for x in range(out.width):
            if p[x,y][3]<170:p[x,y]=(0,0,0,0)
    return out
def groups():
    g=[] # (name, [(dir,file,originx,originy)])
    for k in DEER_KEYS:g.append((f'DEER_{k.upper()}',[('deer-mount',DEER_STARTS[k]+i,128,128) for i in DEER_KEYS[k]]))
    for c in COSTUMES:
        for k in RIDER_KEYS:g.append((f'RIDER_{c.upper()}_{k.upper()}',[(f'deer-{c}',RIDER_STARTS[k]+i,128,128) for i in RIDER_KEYS[k]]))
    g.append(('MONSTER',[('deer-extra-monster',i,400,400) for i in MON]))
    g.append(('ARM1',[('deer-extra-armloop1',i,400,400) for i in range(1,48,6)]))
    g.append(('ARM2',[('deer-extra-armloop2',i,400,400) for i in range(1,48,6)]))
    g.append(('LOG',[('deer-extra-log',i,400,400) for i in list(range(2,10))+[10,11,12,14,15,16,17]]))
    g.append(('OVERLAY',[('deer-extra-overlay',i,400,400) for i in (1,2,10,18,26,34)]))
    g.append(('SHAFT',[('shaft:deer-extra-log',i,400,400) for i in (10,11,12)])) # the translucent light on the floor before each doorway, one flat colour (drawn blended)
    g.append(('LOGFRONT',[('deer-extra-logfront',i,400,400) for i in (10,11,12)]))
    return g
def main():
    G=groups();images=[]
    for name,items in G:
        for d,f,ox,oy in items:
            if d.startswith('shaft:'):images.append((shaft(Image.open(R/f'assets/{d[6:]}/{f}.png').convert('RGBA')),ox,oy,0))
            elif d=='deer-extra-log' and f in (10,11,12):images.append((solid(Image.open(R/f'assets/{d}/{f}.png').convert('RGBA')),ox,oy,0))
            else:images.append((Image.open(R/f'assets/{d}/{f}.png').convert('RGBA'),ox,oy,0))
    atlas=Image.new('RGB',(max(i.width for i,_,_,_ in images),sum(i.height for i,_,_,_ in images)),(0,0,0));y=0
    for im,_,_,_ in images:atlas.paste(im.convert('RGB'),(0,y),im.getchannel('A').point(lambda a:255 if a>=100 else 0));y+=im.height
    pal=atlas.quantize(colors=255,method=Image.Quantize.MEDIANCUT);prgb=pal.getpalette()[:765]
    ds=[0]+[0x8000|(prgb[i]>>3)|((prgb[i+1]>>3)<<5)|((prgb[i+2]>>3)<<10) for i in range(0,765,3)]
    data=bytearray();frames=[];seen={}
    BAYER=[0,8,2,10,12,4,14,6,3,11,1,9,15,7,13,5]
    for im,ox,oy,soft in images:
        a=im.getchannel('A').point(lambda v:255 if v>=100 else 0)
        if soft:
            al=im.getchannel('A');ap=al.load();a=Image.new('L',im.size,0);mp=a.load()
            for yy in range(im.height):
                for xx in range(im.width):
                    v=ap[xx,yy]
                    if v>=200 or v>BAYER[(yy&3)*4+(xx&3)]*14+10:mp[xx,yy]=255
        box=a.getbbox()
        if not box:frames.append((0,0,0,0,0));continue
        q=im.convert('RGB').quantize(palette=pal,dither=Image.Dither.NONE);x,y,r,b=box
        block=bytes(q.getpixel((xx,yy))+1 if a.getpixel((xx,yy)) else 0 for yy in range(y,b) for xx in range(x,r))
        key=(r-x,b-y,x-ox,y-oy,block)
        if key in seen:frames.append(frames[seen[key]]);continue
        seen[key]=len(frames);off=len(data);data.extend(pack(block));frames.append((off,x-ox,y-oy,r-x,b-y))
    out=['#ifndef DEER_ACTOR_ART_H\n#define DEER_ACTOR_ART_H\n#include <stdint.h>\n#include "castle_art.h"\n/* Generated by tools/deer_actors.py: deer, riders (blue, orange, red, green), Mill Monster, logs. */\n']
    out.append(f'#define DEER_ACTOR_PIXELS_MAX {max(f[3]*f[4] for f in frames)}\n')
    first=0;names=[];table=[]
    for name,items in G:names.append(f'DA_{name}={len(table)}');table.append((first,len(items)));first+=len(items)
    out.append('enum {'+','.join(names)+f',DA_GROUPS={len(table)}}};\n')
    out.append('typedef struct {uint16_t first,count;} DeerGroup;\n')
    out.append('static const DeerGroup deer_groups[%d]={'%len(table)+','.join('{%d,%d}'%t for t in table)+'};\n')
    out.append(arr('deer_actor_palette','uint16_t',ds));out.append(arr('deer_actor_pixels','uint8_t',list(data)))
    out.append('static const ArtFrame deer_actor_frames[%d]={'%len(frames)+','.join('{%d,%d,%d,%d,%d}'%f for f in frames)+'};\n')
    out.append('''static inline int deer_actor_decode(unsigned id,uint8_t*out){
 if(id>=%d||!out)return 0;
 const ArtFrame*f=&deer_actor_frames[id];unsigned at=f->offset,left=(unsigned)f->w*f->h;
 while(left){
  if(at>=sizeof(deer_actor_pixels))return 0;
  unsigned token=deer_actor_pixels[at++],n=(token&127)+1;if(n>left)return 0;
  if(token&128){if(at>=sizeof(deer_actor_pixels))return 0;unsigned v=deer_actor_pixels[at++];for(unsigned j=0;j<n;j++)*out++=(uint8_t)v;}
  else{if(n>sizeof(deer_actor_pixels)-at)return 0;for(unsigned j=0;j<n;j++)*out++=deer_actor_pixels[at++];}
  left-=n;
 }return 1;
}
#endif
'''%len(frames))
    (R/'generated/deer_actor_art.h').write_text(''.join(out))
    print('frames',len(frames),'distinct',len(seen),'pixel bytes',len(data),'max',max(f[3]*f[4] for f in frames))
if __name__=='__main__':main()
