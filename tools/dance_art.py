"""PLAYER dance1..dance4 (sprites 1826, 1832, 1839, 1823) for the four knights and the grey party knights of the Barracks.
python dance_art.py prepare   export frames with FFDec (zoom 0.5) into assets/dance-<costume>
python dance_art.py convert   pack into generated/dance_art.h (pixel stream goes into the keep bank)"""
from pathlib import Path
import xml.etree.ElementTree as ET,sys
from PIL import Image
import rider_art as ra
from rider_art import pack,arr
R=ra.R
COSTUMES=[('blue',3),('orange',5),('red',4),('green',2),('gray',6)]
DANCES=[('dance1',1826,12,1),('dance2',1832,48,3),('dance3',1839,78,4),('dance4',1823,5,1)] # name, sprite, frames, stride kept
def prepare(only=None):
    for name,variant in COSTUMES:
        if only and name!=only:continue
        r,definitions=ra.costume_defs(name,variant);tags=r.find('tags');tags.clear();tags.extend(definitions);total=0
        for dn,sid,count,stride in DANCES:
            ET.SubElement(tags,'item',type='RemoveObject2Tag',depth='1',forceWriteAsLong='false')
            p=ET.SubElement(tags,'item',type='PlaceObject2Tag',characterId=str(sid),depth='1',forceWriteAsLong='false',placeFlagHasCharacter='true',placeFlagHasMatrix='true',placeFlagMove='false',placeFlagHasClipActions='false',placeFlagHasClipDepth='false',placeFlagHasColorTransform='false',placeFlagHasName='false',placeFlagHasRatio='false')
            ET.SubElement(p,'matrix',type='MATRIX',hasRotate='false',hasScale='false',translateX='0',translateY='0',rotateSkew0='0.0',rotateSkew1='0.0',scaleX='1.0',scaleY='1.0',nTranslateBits='1',nRotateBits='0',nScaleBits='0')
            for _ in range(count):ET.SubElement(tags,'item',type='ShowFrameTag',forceWriteAsLong='false')
            total+=count
        r.set('frameCount',str(total));rect=r.find('displayRect')
        for k,v in dict(Xmin=-5120,Xmax=5120,Ymin=-5120,Ymax=2560).items():rect.set(k,str(v))
        xml=R/f'assets/extracted/dance-{name}.xml';ET.ElementTree(r).write(xml,encoding='utf-8',xml_declaration=True)
        swf=xml.with_suffix('.swf');out=R/f'assets/dance-{name}'
        ra.ffdec('-xml2swf',str(xml),str(swf));ra.ffdec('-zoom','0.5','-ignorebackground','-export','frame',str(out),str(swf))
        print(name,len(list(out.glob('*.png'))),flush=True)
def convert():
    images=[];layout=[] # (costume,dance,[indices])
    for name,variant in COSTUMES:
        start=1
        for dn,sid,count,stride in DANCES:
            keys=list(range(0,count,stride)) if name=='gray' or dn in('dance1','dance2') else [] # heroes only use the first two styles, as in the source (the n-th player dances dance n)
            layout.append((name,dn,len(keys)))
            for k in keys:images.append(Image.open(R/f'assets/dance-{name}/{start+k}.png').convert('RGBA'))
            start+=count
    flat=Image.new('RGB',(max(i.width for i in images),sum(i.height for i in images)),(0,0,0));y=0
    for im in images:flat.paste(im.convert('RGB'),(0,y),im.getchannel('A').point(lambda a:255 if a>=100 else 0));y+=im.height
    pal=flat.quantize(colors=255,method=Image.Quantize.MEDIANCUT);prgb=pal.getpalette()[:765]
    ds=[0]+[0x8000|(prgb[i]>>3)|((prgb[i+1]>>3)<<5)|((prgb[i+2]>>3)<<10) for i in range(0,765,3)]
    data=bytearray();frames=[];seen={}
    for im in images:
        a=im.getchannel('A').point(lambda v:255 if v>=100 else 0);box=a.getbbox()
        if not box:frames.append((0,0,0,0,0));continue
        q=im.convert('RGB').quantize(palette=pal,dither=Image.Dither.NONE);x,y,r,b=box
        block=bytes(q.getpixel((xx,yy))+1 if a.getpixel((xx,yy)) else 0 for yy in range(y,b) for xx in range(x,r))
        key=(r-x,b-y,x,y,block)
        if key in seen:frames.append(frames[seen[key]]);continue
        seen[key]=len(frames);frames.append((len(data),x-128,y-128,r-x,b-y));data.extend(pack(block))
    h=['#ifndef DANCE_ART_H','#define DANCE_ART_H','#include <stdint.h>','#include "castle_art.h"','/* Generated by tools/dance_art.py: PLAYER dance1..4 for blue, orange, red, green and the grey party knights. */',
       f'#define DANCE_PIXELS_MAX {max(f[3]*f[4] for f in frames)}']
    first=0;rows=[]
    for name,dn,count in layout:rows.append((first,count));first+=count
    h.append('enum {DANCE_BLUE,DANCE_ORANGE,DANCE_RED,DANCE_GREEN,DANCE_GRAY,DANCE_COSTUMES};enum {DANCE_1,DANCE_2,DANCE_3,DANCE_4,DANCE_STYLES};')
    h.append('typedef struct {uint16_t first,count;} DanceClip;')
    h.append('static const DanceClip dance_clips[DANCE_COSTUMES][DANCE_STYLES]={'+','.join('{'+','.join('{%d,%d}'%rows[c*4+d] for d in range(4))+'}' for c in range(5))+'};')
    h.append(arr('dance_palette','uint16_t',ds));h.append(arr('dance_pixels','uint8_t',list(data)))
    h.append('static const ArtFrame dance_frames[%d]={'%len(frames)+','.join('{%d,%d,%d,%d,%d}'%f for f in frames)+'};')
    h.append('''static inline int dance_decode(unsigned id,uint8_t*out){
 if(id>=%d||!out)return 0;
 const ArtFrame*f=&dance_frames[id];unsigned at=f->offset,left=(unsigned)f->w*f->h;
 while(left){
  if(at>=sizeof(dance_pixels))return 0;
  unsigned token=dance_pixels[at++],n=(token&127)+1;if(n>left)return 0;
  if(token&128){if(at>=sizeof(dance_pixels))return 0;unsigned v=dance_pixels[at++];for(unsigned j=0;j<n;j++)*out++=(uint8_t)v;}
  else{if(n>sizeof(dance_pixels)-at)return 0;for(unsigned j=0;j<n;j++)*out++=dance_pixels[at++];}
  left-=n;
 }return 1;
}
#endif'''%len(frames))
    (R/'generated/dance_art.h').write_text(chr(10).join(h)+chr(10));print('frames',len(frames),'distinct',len(seen),'bytes',len(data),'max',max(f[3]*f[4] for f in frames),layout[:5])
if __name__=='__main__':
    if sys.argv[1]=='prepare':prepare(sys.argv[2] if len(sys.argv)>2 else None)
    else:convert()
