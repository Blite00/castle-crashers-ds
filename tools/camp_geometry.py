"""LEVEL20 floor bands, waypoints and markers in DS world units. World x = (source x + 4700)/2, y = (source y + 800)/2 (origin of the 'camp' row of
prepare_campaign_war.py). A column holds one or two walkable bands (the plain and, at the fortress, the top deck); only the ladder joins them."""
from pathlib import Path
import struct,math
import xml.etree.ElementTree as E
R=Path(__file__).resolve().parents[1]
OX,OY=4700,800;W=6450;H=448
b=(R/'assets/extracted/bsp20.bin').read_bytes();n=struct.unpack_from('<I',b,16)[0]//8
edges=[struct.unpack_from('<8f',b,20+i*32)[1:6] for i in range(n)]
def bands(wx):
    ys=sorted(y1+(y2-y1)*(wx-x1)/(x2-x1) for x1,y1,x2,y2,k in edges if int(k) in (1,2,3,400,700) and x1!=x2 and min(x1,x2)<=wx<max(x1,x2))
    out=[]
    for i in range(0,len(ys)-1,2):out.append((ys[i],ys[i+1]))
    return out
cols=[]
for x in range(W):
    bs=bands(x*2-OX)
    ok=[(lo,hi) for lo,hi in bs if (hi-lo)/2-10>=4]  # slivers between nested outlines are not floor
    if len(ok)>2:ok=sorted(sorted(ok,key=lambda b:b[0]-b[1])[:2])
    cols.append([(max(0,math.ceil((lo+OY)/2)+5),min(H-1,math.floor((hi+OY)/2)-5)) for lo,hi in ok])
rows=[]
for v in cols:
    v=[t for t in v if t[0]<=t[1]]
    while len(v)<2:v.append((448,0))
    if len(v)>2:v=v[:2]
    rows.append((v[0][0],v[0][1],v[1][0],v[1][1]))
# The ladder (BSP edges 700, sl_bot0 and sl_top0): a vertical shaft joining the plain and the top deck. Up and down walk it, as f_SideLadder does.
LADDER=(5074,5110)
for x in range(LADDER[0],LADDER[1]+1):
    lo=min(r for r in (rows[x][0],rows[x][2]) if r<448);hi=max(rows[x][1],rows[x][3])
    rows[x]=(min(lo,102),max(hi,360),448,0)
runs=[]
for x,r in enumerate(rows):
    if not runs or runs[-1][1:]!=r:runs.append((x,*r))
def wx(sx):return round((sx+OX)/2)
def wy(sy):return round((sy+OY)/2)
off=20+n*32;vals=struct.unpack_from(f'<{(len(b)-off)//4}f',b,off)
wps=[]
for k in range(0,len(vals)-2,3):
    x,y,f=vals[k:k+3]
    if x==0 and y==0:break
    wps.append((wx(x),wy(y)))
root=E.parse(R/'assets/extracted/level20-full.xml').getroot();ts=root.find('tags')
scene=next(t for t in ts if t.get('type')=='DefineSpriteTag' and t.get('spriteId')=='386')
marks={}
for t in scene.find('subTags'):
    if t.get('type','').startswith('PlaceObject') and t.get('name') and t.find('matrix') is not None:
        m=t.find('matrix');sx=int(m.get('translateX','0'))/20;sy=int(m.get('translateY','0'))/20
        marks[t.get('name')]=(wx(sx),wy(sy))
keep=['p1_1','p2_1','p1_2','p2_2','p1_3','p2_3','p1_4','p2_4','p3_4','p4_4','p1_5','p2_5','door1','door2','door3','edge_left','edge_right','sl_bot0','sl_top0','boss','boss_cam','cinema_cam','camera_target','bossdoor','weapon_pt','animal_pt','mud','campfire','hawkster','spawn1','spawn2','spawn3','spawn4','abs_bottom','leaf_end']
h='#ifndef CAMP_GEOMETRY_H\n#define CAMP_GEOMETRY_H\n#include <stdint.h>\n/* LEVEL20 half scale, origin (-4700,-800); 5 px foot margin. Generated by tools/camp_geometry.py. */\n'
h+=f'#define CAMP_WIDTH {W}\n'
import struct as _st
_data=b''.join(_st.pack('<5H',*r) for r in runs)
NL=chr(10)
h+=f'static const uint8_t camp_floor_runs_data[{len(_data)}] __attribute__((aligned(4)))={{'+NL+''.join(','.join(map(str,_data[i:i+32]))+','+NL for i in range(0,len(_data),32))+'};'+NL+'#define camp_floor_runs ((const uint16_t(*)[5])(camp_floor_runs_data))'+NL
h+='''static inline int camp_floor_open(int x,int y){
 unsigned lo=0,hi=%d;
 if(x<0||x>=%d||y<0)return 0;
 while(lo+1<hi){unsigned mid=(lo+hi)/2;if(camp_floor_runs[mid][0]<=(unsigned)x)lo=mid;else hi=mid;}
 const uint16_t *r=camp_floor_runs[lo];
 return (y>=(int)r[1]&&y<=(int)r[2])||(y>=(int)r[3]&&y<=(int)r[4]);
}
'''%(len(runs),W)
h+=f'#define CAMP_WAYPOINT_COUNT {len(wps)}\n'
h+=f'static const int16_t camp_waypoints[{len(wps)}][2]={{'+','.join('{%d,%d}'%w for w in wps)+'};\n'
for k in keep:
    if k in marks:h+=f'#define CAMP_{k.upper()}_X {marks[k][0]}\n#define CAMP_{k.upper()}_Y {marks[k][1]}\n'
h+='#endif\n'
(R/'generated/camp_geometry.h').write_text(h)
print('runs',len(runs),'two-band columns',sum(1 for r in rows if r[2]<=r[3]),'first open',next(i for i,r in enumerate(rows) if r[0]<=r[1]),'last',max(i for i,r in enumerate(rows) if r[0]<=r[1]))
print(wps);print({k:marks[k] for k in keep if k in marks})
