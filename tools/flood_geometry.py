"""LEVEL23 Flooded Castle: floor bounds and markers in DS world units. World x = (source x + 600)/2, world y = (source y + 560)/2
(the origin of the 'flood' row of prepare_campaign_war.py). BSP23 is a skewed rectangle: left x -440, right x 1207, top edge from y -172.5 to -198.3,
bottom edge y 54. The usual 5 px foot margin applies."""
from pathlib import Path
import struct,math
R=Path(__file__).resolve().parents[1]
OX,OY=600,560;W=1000;H=448
b=(R/'assets/extracted/bsp23.bin').read_bytes();n=struct.unpack_from('<I',b,16)[0]//8
edges=[struct.unpack_from('<8f',b,20+i*32)[1:6] for i in range(n)]
valid=[]
for x in range(W):
    wx=x*2-OX;ys=[]
    for x1,y1,x2,y2,k in edges:
        if int(k) in (1,2,3) and x1!=x2 and min(x1,x2)<=wx<max(x1,x2):ys.append(y1+(y2-y1)*(wx-x1)/(x2-x1))
    valid.append((max(0,math.ceil((min(ys)+OY)/2)+5),min(H-1,math.floor((max(ys)+OY)/2)-5)) if len(ys)>=2 else None)
runs=[]
for x,v in enumerate(valid):
    if v is None or v[0]>v[1]:v=(448,0)
    if not runs or runs[-1][1:]!=v:runs.append((x,*v))
def wx(sx):return round((sx+OX)/2)
def wy(sy):return round((sy+OY)/2)
marks={'P1_START':(47,-91),'P2_START':(494,-81),'P3_START':(267,-133),'P4_START':(244,-20),'E_SPAWN':(817,-160),'ROCK_SPAWN':(942,-171),'BOSS':(519,-69),'KINGBOAT':(-160,-57),'DOOR':(-434,-65)}
h='#ifndef FLOOD_GEOMETRY_H\n#define FLOOD_GEOMETRY_H\n#include <stdint.h>\n/* BSP23 corridor, half scale, origin (-600,-560); 5 px foot margin. Generated by tools/flood_geometry.py. */\n'
h+=f'#define FLOOD_WIDTH {W}\n'
h+=f'static const uint16_t flood_floor_runs[{len(runs)}][3]={{'+','.join('{%d,%d,%d}'%r for r in runs)+'};\n'
h+='''static inline unsigned flood_floor_bound(unsigned x,unsigned bound){
 unsigned lo=0,hi=%d;
 if(x>=%d)return bound?0:448;
 while(lo+1<hi){unsigned mid=(lo+hi)/2;if(flood_floor_runs[mid][0]<=x)lo=mid;else hi=mid;}
 return flood_floor_runs[lo][bound?2:1];
}
#define flood_floor_min(x) flood_floor_bound((x),0)
#define flood_floor_max(x) flood_floor_bound((x),1)
'''%(len(runs),W)
for k,(sx,sy) in marks.items():h+=f'#define FLOOD_{k}_X {wx(sx)}\n#define FLOOD_{k}_Y {wy(sy)}\n'
h+='#endif\n'
(R/'generated/flood_geometry.h').write_text(h)
print('runs',len(runs),'open x',next(i for i,v in enumerate(valid) if v),max(i for i,v in enumerate(valid) if v),{k:(wx(a),wy(c)) for k,(a,c) in marks.items()})
