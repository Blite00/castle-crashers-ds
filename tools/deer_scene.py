"""LEVEL22 (deer ride through the mill) world art, 2 players. python deer_scene.py
The original mill clip (sprite 88) slides a flume past the camera and loops frames 177..287 (period ~953 DS px). The DS world is that
flume laid out flat with one extra copy of the loop tile, so the chase can wrap back by LOOP_PERIOD without a visible seam:
  [0,A) flume start | [A,A+P) tile | [A+P,A+2P) tile | flume tail | forest dock (from the static scene 243 bake)
Writes assets/campaign-deer/1.png (world, 448 rows), assets/campaign-deer-layers.json and generated/deer_layout.h."""
from pathlib import Path
from PIL import Image
import json
R=Path(__file__).resolve().parents[1]
P=953;A=300;TOP_CUT=25
F=Image.open(R/'assets/l22m/DefineSprite_88/300.png').convert('RGBA');F=F.crop(F.getbbox())
static=Image.open(R/'assets/campaign-deer-static.png').convert('RGBA') if (R/'assets/campaign-deer-static.png').exists() else Image.open(R/'assets/campaign-deer/1.png').convert('RGBA')
if not (R/'assets/campaign-deer-static.png').exists():static.save(R/'assets/campaign-deer-static.png')
head=F.crop((0,TOP_CUT,A,F.height));tile=F.crop((A,TOP_CUT,A+P,F.height));tail=F.crop((A+P,TOP_CUT,F.width,F.height))
# Forest dock: the static bake right of the flume end (plank end found by the first fully transparent plank column).
fx=3140;forest=static.crop((fx,0,static.width,400))
ph=head.height
width=head.width+2*P+tail.width+forest.width
world=Image.new('RGBA',(width,448),(0,0,0,0));x=0
for part in (head,tile,tile,tail):world.alpha_composite(part,(x,0));x+=part.width
forest_x=x;world.alpha_composite(forest,(x,0));x+=forest.width
(R/'assets/campaign-deer').mkdir(exist_ok=True);world.save(R/'assets/campaign-deer/1.png')
(R/'assets/campaign-deer-layers.json').write_text(json.dumps(dict(level=22,origin=[0,0],size=[width,448],layers=[])))
h=f'''#ifndef DEER_LAYOUT_H
#define DEER_LAYOUT_H
/* Generated by tools/deer_scene.py. DS world units. */
#define DEER_WIDTH {width}
#define DEER_LOOP_START {A}
#define DEER_LOOP_PERIOD {P}
#define DEER_FLUME_END {forest_x}
#define DEER_LANE_TOP 180
#define DEER_LANE_BOTTOM 287
#endif
'''
(R/'generated/deer_layout.h').write_text(h);print('world',width,'forest at',forest_x,'head',head.size,'tile',tile.size,'tail',tail.size)
