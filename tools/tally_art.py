"""Original post-level score sign (MAIN sprite 63 'tally' clip: wooden sign with skull, gold bag and XP icons) for generated/tally_art.h.
python tally_art.py   (needs build/appdata FFDec export in assets/tally, zoom 0.5)"""
from pathlib import Path
from PIL import Image
from rider_art import pack,arr
R=Path(__file__).resolve().parents[1]
D=R/'assets/tally/DefineSprite_63'
final=Image.open(D/'40.png').convert('RGBA');box=final.getchannel('A').point(lambda a:255 if a>=100 else 0).getbbox()
panel=final.crop(box);top0=box[1]
drop=[]
for f in range(2,17):
    b=Image.open(D/f'{f}.png').convert('RGBA').getchannel('A').point(lambda a:255 if a>=100 else 0).getbbox()
    drop.append((b[1]-top0) if b else -300)
flat=Image.new('RGB',panel.size,(0,0,0));flat.paste(panel.convert('RGB'),(0,0),panel.getchannel('A').point(lambda a:255 if a>=100 else 0))
pal=flat.quantize(colors=255,method=Image.Quantize.MEDIANCUT);prgb=pal.getpalette()[:765]
ds=[0]+[0x8000|(prgb[i]>>3)|((prgb[i+1]>>3)<<5)|((prgb[i+2]>>3)<<10) for i in range(0,765,3)]
q=panel.convert('RGB').quantize(palette=pal,dither=Image.Dither.NONE);al=panel.getchannel('A').point(lambda a:255 if a>=100 else 0)
block=bytes(q.getpixel((x,y))+1 if al.getpixel((x,y)) else 0 for y in range(panel.height) for x in range(panel.width))
data=pack(block)
h=['#ifndef TALLY_ART_H','#define TALLY_ART_H','#include <stdint.h>','/* Generated by tools/tally_art.py from MAIN sprite 63 (the score tally sign). */',
   f'#define TALLY_W {panel.width}',f'#define TALLY_H {panel.height}',
   f'static const int16_t tally_drop[{len(drop)}]={{'+','.join(map(str,drop))+'}; /* sign top relative to its resting place, source frames 2..16 */',
   arr('tally_palette','uint16_t',ds),arr('tally_pixels','uint8_t',list(data)),
'''static inline int tally_decode(uint8_t *out){
 unsigned at=0,left=TALLY_W*TALLY_H;
 while(left){
  if(at>=sizeof(tally_pixels))return 0;
  unsigned token=tally_pixels[at++],n=(token&127)+1;if(n>left)return 0;
  if(token&128){if(at>=sizeof(tally_pixels))return 0;unsigned v=tally_pixels[at++];for(unsigned j=0;j<n;j++)*out++=(uint8_t)v;}
  else{if(n>sizeof(tally_pixels)-at)return 0;for(unsigned j=0;j<n;j++)*out++=tally_pixels[at++];}
  left-=n;
 }return 1;
}
#endif''']
(R/'generated/tally_art.h').write_text(chr(10).join(h)+chr(10))
panel.save(R/'build/tally_panel.png');print(panel.size,drop,len(data))
